"""store/listing_ios.md の「説明」を、暦(六曜・旧暦・祝日の計算)から始まる形に組み替える(App Store 4.3(a) 対策)。
書いてある事実は元の説明文と同じ。何度流しても同じ結果。python tools/rewrite_desc_koyomi.py"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESC = """大安か、仏滅か。旧暦では今日は何日か。
ひよりごよみは、六曜と旧暦を端末の中で天文計算して、月の表に並べるカレンダーです。新月と太陽の位置から暦を求めるので、電波がなくても表示されます。計算の結果は、国立天文台が公表している新月の時刻と1分以内で合うことを確かめています。

祝日も「国民の祝日に関する法律」の決まりから端末の中で計算します。振替休日と国民の休日も出ます。

予定はスタンプで貼ります。スタンプを選んで日付を押すと、その日に貼られます。シフトの「早」「遅」「休」、給料日、通院、誕生日などを、押していくだけで書き込めます。日付ごとに枠で区切った月の表に、予定とスタンプ、祝日、六曜が並びます。色は9色から選べます。

ふだん使いの機能もそろえました。予定のコピー(ほかの日にいくつでも貼れます)、くり返し(毎日・毎週・毎月・毎年、2週ごとなども)と「この日だけ変える・消す」、よく使う予定を履歴からワンタップで入力、過去の予定とメモの検索、日ごとのメモ、予定のお知らせ(何分前・前の日の夜など)。

端末のカレンダー(iPhoneのカレンダーなど)から予定を読み込めます。読むだけで、端末のカレンダーは書き換えません。バックアップはファイルに書き出して読み込めます。

ひよりプラス(買い切り 500円・月額なし)では、スタンプ全136種(無料は20種)、着せ替え8種(無料は2種)、色に「仕事」「家族」などの名前を付ける、今日の予定のまとめ通知、自動バックアップ(1日1回、7日分)が使えます。

アカウント登録はいりません。予定はこの端末の中だけに保存し、外へ送りません。広告はありません。無料のままでも予定の追加・編集・コピー・検索・お知らせなど、基本の機能はすべて使えます。"""

p = os.path.join(ROOT, "store", "listing_ios.md")
s = open(p, encoding="utf-8").read()
s2 = re.sub(r"(## 説明\n).*?(?=\n## キーワード)", lambda m: m.group(1) + DESC + "\n", s, count=1, flags=re.S)
assert s2 != s or DESC in s
open(p, "w", encoding="utf-8", newline="").write(s2)
open(os.path.join(ROOT, "store", "desc_ios.txt"), "w", encoding="utf-8", newline="").write(DESC)
print(len(DESC), "字")
