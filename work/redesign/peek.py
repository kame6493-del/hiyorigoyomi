"""作り直し中の画面をざっと撮る(確認用)。python work/redesign/peek.py [幅]"""
import os, sys
from playwright.sync_api import sync_playwright
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'peek')
os.makedirs(OUT, exist_ok=True)
W = int(sys.argv[1]) if len(sys.argv) > 1 else 375
H = {375: 812, 430: 932}.get(W, 812)
DEMO = os.path.join(HERE, '..', '..', 'scripts', 'demo_backup.json')
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': W, 'height': H}, device_scale_factor=2, locale='ja-JP', timezone_id='Asia/Tokyo')
    pg = ctx.new_page()
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
    pg.clock.install(time='2026-10-03T10:00:00+09:00'); pg.clock.resume()
    pg.goto('http://localhost:47391/'); pg.wait_for_selector('.month'); pg.wait_for_timeout(800)
    def s(n): pg.wait_for_timeout(350); pg.screenshot(path=os.path.join(OUT, f'{W}_{n}.png'))
    s('01_welcome')
    pg.click('text=はじめる'); s('02_guide1')
    pg.click('text=つぎへ'); s('03_guide2')
    pg.click('text=つぎへ'); s('04_guide3')
    pg.click('text=カレンダーをひらく'); pg.wait_for_timeout(300); s('05_empty')
    pg.click('button[aria-label="その他"]'); pg.set_input_files('[data-testid="backup-file"]', DEMO)
    pg.click('text=今の予定を消して置き換える'); pg.wait_for_timeout(2500)
    s('10_settings'); pg.mouse.wheel(0, 900); s('11_settings2'); pg.mouse.wheel(0, 900); s('12_settings3'); pg.mouse.wheel(0, 1200); s('13_settings4')
    pg.click('button[aria-label="もどる"]')
    pg.locator('.cell[data-date="2026-10-07"]').click(); s('06_month')
    pg.click('.dp-item-main >> nth=0'); s('07_editor')
    pg.click('.ed-row:has-text("色")'); s('08_editor_color')
    pg.click('.ed-row:has-text("くり返し")'); s('08b_editor_repeat')
    pg.click('button[aria-label="やめる"]')
    pg.click('.stamp-pill'); s('09_picker')
    pg.click('.stamp-cell[aria-label="休み"]')
    for d in ['2026-10-04']:
        pg.locator(f'.cell[data-date="{d}"]').click()
    s('14_paste')
    pg.click('.paste-bar >> text=おわる'); pg.wait_for_timeout(2300)
    pg.click('button[aria-label="さがす"]'); pg.fill('.search-box input', '歯医者'); pg.locator('.search-box input').blur(); s('15_search')
    pg.click('button[aria-label="もどる"]')
    pg.click('button[aria-label="その他"]'); pg.click('.plus-card'); s('16_paywall'); pg.mouse.wheel(0, 900); s('17_paywall2')
    print('errors', errs)
    b.close()
